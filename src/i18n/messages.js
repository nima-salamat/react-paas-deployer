export function normalizeLanguage(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (normalized === "fa" || normalized.startsWith("fa-")) return "fa";
  if (normalized === "en" || normalized.startsWith("en-")) return "en-us";
  return null;
}

export function translateText(value, language = "en-us") {
  const source = String(value ?? "");
  if (normalizeLanguage(language) !== "fa") return source;
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const key = source.slice(leading.length, source.length - trailing.length || undefined);
  return leading + (fa[key] ?? key) + trailing;
}

